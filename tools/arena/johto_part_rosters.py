#!/usr/bin/env python3
"""Matt (Option 1): per-part Johto arena-art rosters. Priority order: story-scene mons,
gym leader aces, Elite Four / Red / boss aces, likely player starters. Species outside a
part's roster keep their encounters and battle with the native Gen 1-3 sprites.
Writes .arena-dev/pmd/sprites_p{1,2,3}.inc filtered from sprites.inc, greedily in
priority order under each part's byte budget (argv[1], default 1,741,523 minus margin)."""
import os, re, sys, json
R = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); os.chdir(R)
# Measured: non-art ROM per part = built ROM minus art bytes (2026-10-23 builds); 85% cap = 28,521,267 B, 15 KB margin.
BUDGETS = {1: 1_123_000, 2: 1_133_000, 3: 1_103_000}
PRIO = {
 1: [# story: Chief A, J8 sailor; Show SJ1-SJ10 (Pikachu, Johto starters, Heracross, Noctowl, Charizard, Miltank, Ampharos)
     198, 41, 147, 72, 67, 119, 25, 152, 155, 158, 214, 164, 6, 241, 181,
     # gym aces Falkner..Jasmine (+Morty, Jasmine Magnemite line)
     17, 123, 94, 208, 82,
     # rival / boss aces
     153, 156, 159, 93, 24,
     # likely starters' lines / early partners
     16, 161, 163, 179, 180, 74, 66],
 2: [# story: Chief B/C, J13 boss; Show SJ11-SJ13 (Lugia, Charizard, Gary Blastoise, Harrison Blaziken) + partners
     198, 42, 215, 229, 148, 169, 130, 110, 89, 248, 249, 6, 9, 257, 25, 214, 164, 181,
     # gym aces Chuck, Pryce, Clair
     62, 221, 230,
     # Elite Four + Lance
     178, 68, 197, 149,
     # starters' finals
     154, 157, 160, 154, 24, 110],
 3: [# story: Chief D/Full; Show SJ14-SJ18 (Regis, old squad) + partners
     198, 169, 215, 229, 130, 149, 248, 377, 378, 379, 1, 7, 99, 89, 128, 25, 6,
     # Frontier Brain aces (Emerald brains)
     144, 145, 146, 376, 65, 143,
     # Kanto gym aces
     95, 121, 26, 45, 49, 126, 18,
     # Red
     3, 9, 196],
}
src = open('.arena-dev/pmd/sprites_all386.inc').read()
head, rest = src.split('\n', 1)
tbl = rest.index('\nstatic const struct ArenaSpriteSet') if '\nstatic const struct ArenaSpriteSet' in rest else None
m = re.search(r'\n[^\n]*sPmdSets\[\][^\n]*\n', rest)
defs, table = rest[:m.start()], rest[m.end():]
blocks = {}
for line in defs.split('\n'):
    k = re.search(r'sPmd\w*?(\d{4})', line)
    if k: blocks.setdefault(int(k.group(1)), []).append(line)
rows = {int(re.search(r'sPmdPal(\d{4})', r).group(1)): r.rstrip(',') for r in table.split('\n') if 'sPmdPal' in r}
cost = lambda n: os.path.getsize(f'.arena-dev/pmd/{n:04d}.blob') + os.path.getsize(f'.arena-dev/pmd/{n:04d}.gbapal')
out = {}
for p, order in PRIO.items():
    chosen, used, skipped = [], 0, []
    for n in order:
        if n in chosen: continue
        if n not in blocks:
            skipped.append((n, 'no art')); continue
        if used + cost(n) > BUDGETS[p]:
            skipped.append((n, cost(n))); continue
        chosen.append(n); used += cost(n)
    with open(f'.arena-dev/pmd/sprites_p{p}.inc', 'w') as f:
        f.write(f'// Generated by johto_part_rosters.py (part {p}); {len(chosen)} species, {used} art bytes.\n')
        for n in chosen: f.write('\n'.join(blocks[n]) + '\n')
        f.write(m.group(0).lstrip('\n'))
        f.write(',\n'.join(rows[n] for n in chosen) + '\n};\n')
    out[p] = dict(species=chosen, bytes=used, skipped=skipped)
    print(p, len(chosen), used, 'skipped', skipped)
json.dump(out, open('tools/arena/johto_part_rosters.json', 'w'), indent=1)
