#!/usr/bin/env python3
# Matt D3: which maps belong to a later part. Writes src/data/arena_part_maps.h
import json,re,sys
sys.path.insert(0,'tools/arena')
src=open('tools/arena/measure_johto_parts.py').read()
P2=set(re.search(r"P2=set\('([^']*)'",src).group(1).split())
kanto=re.compile(r'^(ROUTE([1-9]|1\d|2[0-5]|28)(_|$)|PALLET|VIRIDIAN|PEWTER|CERULEAN|VERMILION|LAVENDER|CELADON|SAFFRON|FUCHSIA|CINNABAR|MT_MOON|ROCK_TUNNEL|DIGLETTS|SEAFOAM|MT_SILVER|VICTORY_ROAD_KANTO|VICTORY_ROAD_MOLTRES|SAFARI_ZONE|INDIGO|POWER_PLANT|UNDERGROUND_PATH|SILPH|POKEMON_TOWER|CERULEAN_CAVE|S_S_ANNE)')
p2pre=re.compile(r'^(ROUTE(4[0-6]|2[67])(_|$)|CIANWOOD|WHIRL_ISLANDS|MAHOGANY|LAKE_OF_RAGE|ROCKET_HIDEOUT|ICE_PATH|BLACKTHORN|DRAGONS_DEN|DARK_CAVE_NORTH|MT_MORTAR|TOHJO_FALLS|VICTORY_ROAD_(1F|B1F|B2F)|TIN_TOWER|INDIGO_PLATEAU|SEAFOAM_?NONE)')
d=json.load(open('data/maps/map_groups.json'))
out={2:[],3:[]}
for gi,g in enumerate(d['group_order']):
    for ni,m in enumerate(d[g]):
        mid=json.load(open(f'data/maps/{m}/map.json'))['id'][4:]
        p=2 if (mid in P2 or p2pre.search(mid)) else 3 if kanto.search(mid) else 0
        if p: out[p].append((gi<<8|ni,mid))
with open('src/data/arena_part_maps.h','w') as f:
    f.write('// Generated by tools/arena/gen_part_maps.py. Maps owned by Johto P2 / P3.\n')
    for p in (2,3):
        f.write(f'static const u16 sArenaPart{p}Maps[] = {{\n')
        for v,mid in out[p]: f.write(f'    0x{v:04X}, // {mid}\n')
        f.write('};\n')
print(len(out[2]),len(out[3]))
