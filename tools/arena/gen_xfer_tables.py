# Generates series transfer tables (pret FR/EA <-> pokeemerald-expansion Johto).
import sys
from xfer_consts import load
FR,EA,JO='/workspace/fr/ws','/workspace/ea/ws','/workspace/johto/ws'
def items(ws): return load(ws,'constants/items.h','ITEM_')
def species(ws): return load(ws,'constants/species.h','SPECIES_')
def pret_internal_to_national(ws):
    sp=species(ws); nd=load(ws,'constants/pokedex.h','NATIONAL_DEX_'); out={}
    for k,v in sp.items():
        n=nd.get('NATIONAL_DEX_'+k[8:])
        if n and 0<n<=386 and v not in out: out[v]=n
    return out
def name_map(src,dst,limit):
    by={}
    for k,v in src.items():
        if 0<v<limit: by.setdefault(v,[]).append(k)
    out={}
    for v,ns in by.items():
        for n in ns:
            if n in dst: out[v]=dst[n]; break
    return out
def arr(name,typ,n,m,default=0):
    s=[str(m.get(i,default)) for i in range(n)]
    lines=[', '.join(s[i:i+16]) for i in range(0,n,16)]
    return 'static const %s %s[%d] =\n{\n    %s,\n};\n' % (typ,name,n,',\n    '.join(lines))
J_it,J_sp=items(JO),species(JO)
jmaxitem=J_it['ITEM_FIELD_ARROW']
jforms={}
nat={v:k for k,v in J_sp.items() if 0<v<=386}
for k,v in J_sp.items():
    if v>386 and v<2048:
        for b in sorted(nat.values(),key=len,reverse=True):
            if k.startswith(b+'_'): jforms[v]=J_sp[b]; break
pretballs=['MASTER','ULTRA','GREAT','POKE','SAFARI','NET','DIVE','NEST','REPEAT','TIMER','LUXURY','PREMIER']
expball=load(JO,'constants/pokeball.h','BALL_')
def ball_exp_to_pret():
    return {expball['BALL_'+b]:i+1 for i,b in enumerate(pretballs)}
def gen(tree):
    o=['// Generated by tools/arena/gen_xfer_tables.py from the FR/EA/Johto headers. Do not edit.\n']
    if tree=='johto':
        fr=items(FR); ea=items(EA)
        frmax=max(v for k,v in fr.items() if k!='ITEMS_COUNT')+1
        o.append(arr('sXferFrItemToExp','u16',frmax,name_map(fr,J_it,frmax)))
        i2n=pret_internal_to_national(FR)
        o.append(arr('sXferPretSpeciesToNational','u16',412,i2n))
        n2i={n:i for i,n in pret_internal_to_national(EA).items()}
        o.append(arr('sXferNationalToPretSpecies','u16',387,n2i))
        o.append(arr('sXferExpItemToEa','u16',jmaxitem,name_map(J_it,ea,jmaxitem)))
        o.append(arr('sXferExpBallToPret','u8',len(expball)-1,ball_exp_to_pret(),4))
        o.append('#define XFER_FR_ITEM_COUNT %d\n#define XFER_EXP_ITEM_COUNT %d\n'%(frmax,jmaxitem))
    else:
        ea=items(EA)
        o.append(arr('sXferExpItemToEa','u16',jmaxitem,name_map(J_it,ea,jmaxitem)))
        n2i={n:i for i,n in pret_internal_to_national(EA).items()}
        o.append(arr('sXferNationalToPretSpecies','u16',387,n2i))
        o.append('#define XFER_EXP_ITEM_COUNT %d\n'%jmaxitem)
        o.append(arr('sXferExpBallToPret','u8',len(expball)-1,ball_exp_to_pret(),4))
    o.append('static const u16 sXferExpFormToBase[][2] =\n{\n'+''.join('    {%d, %d},\n'%(k,v) for k,v in sorted(jforms.items()))+'};\n')
    return ''.join(o)
open(sys.argv[2],'w').write(gen(sys.argv[1]))
